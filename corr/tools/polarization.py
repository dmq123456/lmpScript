# The measured input
# ----------------------------------------------------------------------
# Reference matrices for the bond along +x, in units of M_UNIT. Shape is
# [[A, 0, 0], [0, B, C], [0, D, E]]; the zeros are imposed by C2x and are
# asserted, not assumed.
M_REFERENCE: dict[int, np.ndarray] = {
    1: np.array([[11.0, 0.0, 0.0],
                 [0.0, 109.0, 139.0],
                 [0.0, -4.0, 5.0]]),
    3: np.array([[-1.0, 0.0, 0.0],
                 [0.0, 16.0, 164.0],
                 [0.0, -12.0, -10.0]]),
}

#: The matrices above are quoted in 1e-5 e Angstrom.
M_UNIT = 1.0e-5

#: Index step along a lattice vector that reaches each neighbour shell. First
#: neighbours are one cell away, third neighbours two, in the same directions.
SHELL_STEP: dict[int, int] = {1: 1, 3: 2}

#: (p, q) means the neighbour at cell (i + p, j + q), i.e. direction p a1 + q a2.
_FAMILY_OFFSETS = ((1, 0), (0, 1), (1, 1))

DEFAULT_SHELLS = (1, 3)

#: 1 e Angstrom in C m, for the areal conversion.
_E_ANGSTROM_IN_C_M = 1.602176634e-19 * 1.0e-10


# ----------------------------------------------------------------------
# Symmetry
# ----------------------------------------------------------------------
def rotation_z(degrees: float) -> np.ndarray:
    t = np.radians(degrees)
    c, s = np.cos(t), np.sin(t)
    return np.array([[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]])


C2X = np.diag([1.0, -1.0, -1.0])
INVERSION = -np.eye(3)


def d3d_operations() -> list[np.ndarray]:
    """The twelve operations of -3m, as C3^k . C2x^b . i^c."""
    identity = np.eye(3)
    return [
        rotation_z(120.0 * k) @ (C2X if b else identity) @ (INVERSION if c else identity)
        for k in range(3)
        for b in (0, 1)
        for c in (0, 1)
    ]


def transform(rotation: np.ndarray, matrix: np.ndarray) -> np.ndarray:
    """M -> det(R) R M R^T, the transformation law of the axial-to-polar tensor."""
    return float(np.linalg.det(rotation)) * rotation @ matrix @ rotation.T


def _angle_of(direction: np.ndarray) -> float:
    """In-plane direction angle in degrees, wrapped to [0, 360)."""
    angle = np.degrees(np.arctan2(direction[1], direction[0])) % 360.0
    return float(angle % 360.0)


def direction_matrices(reference: np.ndarray) -> dict[int, np.ndarray]:
    """{angle in degrees: M} over the orbit of the reference bond along +x.

    Built by acting with the whole group, so the det(R) factor, the stabiliser
    and the bond antisymmetry are all exercised here rather than assumed. An
    operation that maps the reference bond onto one already visited must
    reproduce the same matrix; if it does not, the reference matrix is not
    invariant under its own stabiliser and the frame convention is wrong.
    """
    reference = np.asarray(reference, dtype=float)
    orbit: dict[int, np.ndarray] = {}
    for rotation in d3d_operations():
        direction = rotation @ np.array([1.0, 0.0, 0.0])
        key = int(round(_angle_of(direction))) % 360
        candidate = transform(rotation, reference)
        seen = orbit.get(key)
        if seen is not None and not np.allclose(seen, candidate, atol=1e-9):
            raise ValueError(
                "The reference matrix is not invariant under the stabiliser of its own "
                "bond, so it cannot belong to a D3d-symmetric bond along x. In the "
                "P-3m1 setting used by NiI2 the x axis is a twofold axis, which forces "
                "M[0][1] = M[0][2] = M[1][0] = M[2][0] = 0. Check that a1 is along x "
                "and that the matrix is not quoted in the P-31m setting, which is "
                "rotated by 30 degrees."
            )
        orbit[key] = candidate
    return orbit


def _matrix_for_direction(orbit: dict[int, np.ndarray], direction: np.ndarray,
                          tol_deg: float = 1e-3) -> np.ndarray:
    """The orbit member pointing along `direction`.

    Looked up by the bond's actual Cartesian angle rather than by which lattice
    vector produced it, so a box whose a1 is not along x still gets the right
    matrix -- and a box misaligned with the reference frame raises instead of
    silently using the wrong one.
    """
    angle = _angle_of(direction)
    for key, matrix in orbit.items():
        if min(abs(angle - key), 360.0 - abs(angle - key)) < tol_deg:
            return matrix
    raise ValueError(
        f"Bond direction at {angle:.4f} degrees is not in the D3d orbit of the "
        f"reference bond, whose members are at {sorted(orbit)} degrees. The lattice is "
        "rotated relative to the M matrices -- a 30 degree offset means the matrices "
        "are quoted in the other setting of -3m (P-31m rather than P-3m1)."
    )


# ----------------------------------------------------------------------
# Bonds
# ----------------------------------------------------------------------
class BondFamily(NamedTuple):
    """One set of parallel bonds: every site paired with the same neighbour."""

    shell: int
    offset: tuple[int, int]
    angle: float
    site_i: np.ndarray
    site_j: np.ndarray
    matrix: np.ndarray


def _families_one_layer(
    site_of: np.ndarray,
    n1: int,
    n2: int,
    lattice: np.ndarray,
    shells: tuple[int, ...],
    orbits: dict[int, dict[int, np.ndarray]],
) -> list[BondFamily]:
    # The offsets below count primitive cells, so the bond direction has to be
    # built from the primitive vectors. Taking the box vectors instead is right
    # only when n1 == n2 and silently skews every direction otherwise.
    a1, a2 = lattice[0] / n1, lattice[1] / n2

    families: list[BondFamily] = []
    for shell in shells:
        step = SHELL_STEP[shell]
        if min(n1, n2) <= 2 * step:
            raise ValueError(
                f"A {n1} x {n2} grid is too small for neighbour shell {shell}: the bond "
                f"reaches {step} cell(s) away, so under the periodic wrap it coincides "
                "with its own reverse and would be counted twice. Use a supercell with "
                f"more than {2 * step} cells along both axes, or drop this shell."
            )
        for p, q in _FAMILY_OFFSETS:
            offset = (p * step, q * step)
            direction = offset[0] * a1 + offset[1] * a2
            neighbour = np.roll(site_of, (-offset[0], -offset[1]), axis=(0, 1))
            families.append(BondFamily(
                shell=shell,
                offset=offset,
                angle=_angle_of(direction),
                site_i=site_of.ravel(),
                site_j=neighbour.ravel(),
                matrix=_matrix_for_direction(orbits[shell], direction),
            ))
    return families


def build_families(
    x: np.ndarray,
    y: np.ndarray,
    z: np.ndarray,
    lattice: np.ndarray,
    *,
    shells: tuple[int, ...] = DEFAULT_SHELLS,
    single_layer: bool = True,
    grid: tuple[int, int] | None = None,
    reference: dict[int, np.ndarray] | None = None,
) -> list[list[BondFamily]]:
    """Bond families per layer, each unordered bond appearing exactly once.

    Only the three positive directions of each shell are generated. The other
    three are their reverses, and taking a bond twice with M(-d) = -M(d) and
    S_j x S_i = -(S_i x S_j) would simply double the answer.
    """
    reference = reference or M_REFERENCE
    unknown = sorted(set(shells) - set(SHELL_STEP))
    if unknown:
        raise ValueError(
            f"No neighbour-shell geometry for shell(s) {unknown}. Shells 1 and 3 share "
            "the twofold-axis directions and are generated here; shell 2 points along "
            "the mirrors instead and needs its own four-state mapping, with a matrix of "
            "a different shape."
        )
    missing = sorted(set(shells) - set(reference))
    if missing:
        raise ValueError(f"No reference M matrix supplied for shell(s) {missing}.")

    orbits = {shell: direction_matrices(reference[shell]) for shell in shells}
    positions = np.stack([np.asarray(x, float), np.asarray(y, float), np.asarray(z, float)],
                         axis=1)
    lattice = np.asarray(lattice, dtype=float)

    per_layer: list[list[BondFamily]] = []
    for where, site_of, n1, n2 in layer_grids(positions, lattice, single_layer, grid):
        local = _families_one_layer(site_of, n1, n2, lattice, tuple(shells), orbits)
        per_layer.append([
            family._replace(site_i=where[family.site_i], site_j=where[family.site_j])
            for family in local
        ])
    return per_layer


# ----------------------------------------------------------------------
# The polarization itself
# ----------------------------------------------------------------------
def _unit(vectors: np.ndarray) -> np.ndarray:
    norm = np.linalg.norm(vectors, axis=1, keepdims=True)
    if np.any(norm == 0.0):
        raise ValueError(
            "Some sites carry a zero spin, which has no direction. Drop them with "
            "--drop-zero-vector, or select the magnetic sublattice with --element."
        )
    return vectors / norm


def family_polarization(m: np.ndarray, family: BondFamily) -> np.ndarray:
    """Per-bond contribution M (S_i x S_j) of one family, shape (n_bonds, 3)."""
    chirality = np.cross(m[family.site_i], m[family.site_j])
    return chirality @ family.matrix.T


def layer_polarization(
    m: np.ndarray,
    families_per_layer: list[list[BondFamily]],
    *,
    spin_length: float = 1.0,
) -> np.ndarray:
    """Total P of each layer, shape (n_layers, 3), in e Angstrom.

    Summed over bonds before the matrix product would be equivalent; it is done
    the other way round so that this shares its arithmetic exactly with
    `site_polarization` and the two cannot disagree.
    """
    scale = M_UNIT * spin_length ** 2
    return np.array([
        scale * sum(family_polarization(m, family).sum(axis=0) for family in families)
        for families in families_per_layer
    ])


def site_polarization(
    m: np.ndarray,
    families_per_layer: list[list[BondFamily]],
    n_sites: int,
    *,
    spin_length: float = 1.0,
) -> np.ndarray:
    """Per-site p_i, shape (n_sites, 3), in e Angstrom, with sum_i p_i = P.

    Each bond's contribution is split equally between its two ends, which is
    the same convention topocharge.py uses to spread a triangle's charge over
    its vertices, and for the same reason: tripcolor wants a value per vertex.
    """
    out = np.zeros((n_sites, 3), dtype=float)
    for families in families_per_layer:
        for family in families:
            half = 0.5 * family_polarization(m, family)
            np.add.at(out, family.site_i, half)
            np.add.at(out, family.site_j, half)
    return M_UNIT * spin_length ** 2 * out


def areal_pC_per_m(polarization: np.ndarray, lattice: np.ndarray) -> np.ndarray:
    """P summed over the whole box, in e Angstrom -> areal polarization in pC/m.

    A monolayer has no thickness to divide by, so the honest reduction of a
    two-dimensional dipole density is per unit area of sheet, giving C/m rather
    than the C/m^2 of a bulk ferroelectric. The area is the box's, so for a
    bilayer this is the polarization of the stack, not of one layer.
    """
    lattice = np.asarray(lattice, dtype=float)
    box_area = abs(np.cross(lattice[0][:2], lattice[1][:2]))              # Angstrom^2
    return np.asarray(polarization) * _E_ANGSTROM_IN_C_M / (box_area * 1.0e-20) * 1.0e12


# ----------------------------------------------------------------------
# Frame interface
# ----------------------------------------------------------------------
_FAMILY_CACHE: dict[tuple, list[list[BondFamily]]] = {}


def families_for_frame(frame: dict, cfg: dict | None = None) -> list[list[BondFamily]]:
    """Bond families for one frame, built once and reused.

    The connectivity is cached on the grid shape, so the atom order has to be
    the same in every frame -- LAMMPS guarantees that with
    `dump_modify <id> sort id`.
    """
    cfg = cfg or {}
    lattice = _lattice_from_frame(frame)
    single_layer = bool(cfg.get("single_layer", True))
    grid = grid_from_cfg(cfg)
    shells = tuple(cfg.get("shells") or DEFAULT_SHELLS)
    n_sites = int(frame["x"].size)

    key = (n_sites, single_layer, tuple(grid) if grid else None, shells,
           np.round(lattice, 6).tobytes())
    families = _FAMILY_CACHE.get(key)
    if families is None:
        families = build_families(
            frame["x"], frame["y"], frame["z"], lattice,
            shells=shells, single_layer=single_layer, grid=grid,
        )
        _FAMILY_CACHE[key] = families
    return families


def _spins(frame: dict) -> np.ndarray:
    if "u" not in frame:
        raise ValueError(
            "The polarization needs the spin direction, so --vector is required, e.g. "
            "--vector 'c_outsp[1]' 'c_outsp[2]' 'c_outsp[3]'."
        )
    return _unit(np.stack([frame["u"], frame["v"], frame["w"]], axis=1).astype(float))


def frame_polarization(frame: dict, cfg: dict | None = None) -> np.ndarray:
    """Total P of one frame, shape (n_layers, 3), in e Angstrom."""
    cfg = cfg or {}
    return layer_polarization(
        _spins(frame), families_for_frame(frame, cfg),
        spin_length=float(cfg.get("spin_length", 1.0)),
    )


def frame_site_polarization(frame: dict, cfg: dict | None = None) -> np.ndarray:
    """Per-site p_i of one frame, shape (n_sites, 3), in e Angstrom."""
    cfg = cfg or {}
    return site_polarization(
        _spins(frame), families_for_frame(frame, cfg), int(frame["x"].size),
        spin_length=float(cfg.get("spin_length", 1.0)),
    )


_COMPONENTS = {"x": 0, "y": 1, "z": 2}


def site_density(frame: dict, cfg: dict | None = None, component: str = "norm") -> np.ndarray:
    """One scalar per site for --color px/py/pz/pnorm."""
    p = frame_site_polarization(frame, cfg)
    if component == "norm":
        return np.linalg.norm(p, axis=1)
    return p[:, _COMPONENTS[component]]


