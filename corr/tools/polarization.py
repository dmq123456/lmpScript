# Self-test
# ----------------------------------------------------------------------
def _triangular_lattice(n1: int, n2: int, a: float = 3.9793, c: float = 20.0):
    """Same n1 x n2 supercell topocharge.py tests on, a1 along x."""
    lattice = np.array([[a * n1, 0.0, 0.0],
                        [-0.5 * a * n2, np.sqrt(3.0) / 2.0 * a * n2, 0.0],
                        [0.0, 0.0, c]])
    i, j = np.meshgrid(np.arange(n1), np.arange(n2), indexing="ij")
    frac = np.stack([i.ravel() / n1, j.ravel() / n2, np.zeros(n1 * n2)], axis=1)
    return frac @ lattice, lattice


def _helix(positions, lattice, h, k, e1, e2):
    """Circular spiral with Q = h B1 + k B2 of the supercell, plane (e1, e2).

    Its bond chirality S_i x S_j = sin(Q.d) (e1 x e2) does not depend on
    position, which is what makes the closed form below exact.
    """
    frac = positions @ np.linalg.inv(lattice)
    phase = 2.0 * np.pi * (h * frac[:, 0] + k * frac[:, 1])
    return (np.cos(phase)[:, None] * np.asarray(e1, float)
            + np.sin(phase)[:, None] * np.asarray(e2, float))


def _orthonormal_plane(normal):
    """An (e1, e2) pair spanning the plane normal to `normal`, with e1 x e2 = normal."""
    normal = np.asarray(normal, float) / np.linalg.norm(normal)
    seed = np.array([1.0, 0.0, 0.0]) if abs(normal[0]) < 0.9 else np.array([0.0, 1.0, 0.0])
    e1 = np.cross(normal, seed)
    e1 /= np.linalg.norm(e1)
    return e1, np.cross(normal, e1)


def _cross_matrix(d):
    """[d]_x, the matrix with [d]_x C = d x C."""
    dx, dy, dz = d
    return np.array([[0.0, -dz, dy], [dz, 0.0, -dx], [-dy, dx, 0.0]])


def _knb_reference():
    """The isotropic spin-current form P_ij = e_ij x (S_i x S_j), for the bond along x.

    Symmetry-allowed, so the generator accepts it, and its orbit is known in
    closed form -- which makes it the one case where every generated matrix can
    be checked against an independent expression rather than against itself.
    """
    return {shell: _cross_matrix(np.array([1.0, 0.0, 0.0])) for shell in SHELL_STEP}


def _helix_closed_form(families_per_layer, n1, n2, h, k, e1, e2, spin_length=1.0):
    """P predicted analytically for the helix above, summed over all layers."""
    normal = np.cross(e1, e2)
    total = np.zeros(3)
    for families in families_per_layer:
        for family in families:
            p, q = family.offset
            q_dot_d = 2.0 * np.pi * (h * p / n1 + k * q / n2)
            total += len(family.site_i) * np.sin(q_dot_d) * (family.matrix @ normal)
    return M_UNIT * spin_length ** 2 * total


def _selftest() -> int:
    rng = np.random.default_rng(0)
    failures = 0

    def check(name, ok, detail):
        nonlocal failures
        print(f"[{'PASS' if ok else 'FAIL'}] {name}: {detail}")
        failures += 0 if ok else 1

    def agrees(got, want, scale):
        """Equal to within double-precision accumulation over the whole lattice.

        The tolerance is relative to the size of the answer rather than
        absolute: P grows with the site count, so an absolute bound that passes
        on one supercell fails on a larger one for no reason.
        """
        return float(np.max(np.abs(np.asarray(got) - np.asarray(want)))) < 1e-12 * scale

    # -- symmetry of the input ------------------------------------------------
    for shell, reference in M_REFERENCE.items():
        zeros = [reference[0, 1], reference[0, 2], reference[1, 0], reference[2, 0]]
        check(f"M^{shell} has the C2x shape", np.allclose(zeros, 0.0),
              f"off-axis entries {zeros}")
        check(f"M^{shell} is C2x invariant",
              np.allclose(transform(C2X, reference), reference, atol=1e-12),
              "x is a twofold axis, so P-3m1 and not P-31m")
        check(f"M^{shell} would fail in the other setting",
              not np.allclose(transform(np.diag([1.0, -1.0, 1.0]), reference), reference),
              "a mirror through x would force M[0][0] = 0; it is "
              f"{reference[0, 0]:g}")

    orbit1 = direction_matrices(M_REFERENCE[1])
    check("orbit has six directions", sorted(orbit1) == [0, 60, 120, 180, 240, 300],
          f"angles {sorted(orbit1)}")

    covariant = all(
        np.allclose(orbit1[int(round(_angle_of(R @ np.array([np.cos(np.radians(ang)),
                                                             np.sin(np.radians(ang)), 0.0])))) % 360],
                    transform(R, M), atol=1e-9)
        for R in d3d_operations() for ang, M in orbit1.items()
    )
    check("orbit is D3d covariant", covariant,
          "M(R d) = det(R) R M(d) R^T holds on all 12 x 6 pairs")

    check("antisymmetry falls out of inversion",
          all(np.allclose(orbit1[(ang + 180) % 360], -orbit1[ang], atol=1e-9)
              for ang in (0, 60, 120)),
          "M(-d) = -M(d) was never imposed by hand")

    # The 60 degree direction is the one R_z cannot reach, and substituting it
    # into the rotation formula corrupts exactly two entries.
    naive = transform(rotation_z(60.0), M_REFERENCE[1])
    check("60 deg is not a naive R_z(60) rotation",
          not np.allclose(naive, orbit1[60]) and np.allclose(
              -transform(rotation_z(240.0), M_REFERENCE[1]), orbit1[60], atol=1e-9),
          f"naive form differs by {float(np.max(np.abs(naive - orbit1[60]))):.1f} "
          "in M[0][2]/M[2][0]")

    root3 = np.sqrt(3.0)
    expected120 = np.array([[169 / 2, 49 * root3 / 2, -139 * root3 / 2],
                            [49 * root3 / 2, 71 / 2, -139 / 2],
                            [2 * root3, 2.0, 5.0]])
    check("M^1(120 deg) matches the closed form",
          np.allclose(orbit1[120], expected120, atol=1e-9),
          "R_z(120) M R_z(120)^T as tabulated")

    # -- the polarization on a lattice ----------------------------------------
    for n1, n2 in ((24, 24), (30, 18)):
        positions, lattice = _triangular_lattice(n1, n2)
        families = build_families(*positions.T, lattice, single_layer=True)
        n_sites = n1 * n2
        n_families = len(DEFAULT_SHELLS) * len(_FAMILY_OFFSETS)
        check(f"family count {n1}x{n2}", len(families[0]) == n_families,
              f"{len(families[0])} families, {n_families} expected")
        check(f"every site bonded once per family {n1}x{n2}",
              all(len(np.unique(f.site_i)) == n_sites and len(np.unique(f.site_j)) == n_sites
                  for f in families[0]),
              "no site is missed or repeated")
        check(f"no self-bond {n1}x{n2}",
              all(not np.any(f.site_i == f.site_j) for f in families[0]),
              "every bond joins two distinct sites")

        # Collinear textures have no bond chirality at all, whatever the sign
        # pattern, so they must give exactly zero.
        axis = _unit(rng.normal(size=(1, 3)))[0]
        for name, m in (("ferromagnet", np.tile(axis, (n_sites, 1))),
                        ("random collinear",
                         rng.choice([-1.0, 1.0], size=n_sites)[:, None] * axis)):
            p = layer_polarization(m, families)
            check(f"{name} gives zero P {n1}x{n2}",
                  np.allclose(p, 0.0, atol=1e-18), f"|P| = {float(np.linalg.norm(p)):.3e}")

        # A circular helix: compare against the closed form, and check that the
        # per-site density it produces is uniform, which it must be because the
        # bond chirality does not depend on position.
        basis = np.linalg.qr(rng.normal(size=(3, 3)))[0]
        e1, e2 = basis[0], basis[1]
        h, k = 3, -2
        m = _helix(positions, lattice, h, k, e1, e2)
        p = layer_polarization(m, families)[0]
        predicted = _helix_closed_form(families, n1, n2, h, k, e1, e2)
        check(f"helix matches the closed form {n1}x{n2}",
              np.allclose(p, predicted, atol=1e-14, rtol=1e-10),
              f"P = {np.array2string(p, precision=6)}")

        p_site = site_polarization(m, families, n_sites)
        check(f"helix sums over sites to P {n1}x{n2}",
              agrees(p_site.sum(axis=0), p, float(np.linalg.norm(p))),
              "sum_i p_i = P")
        spread = float(np.max(np.abs(p_site - p_site.mean(axis=0))))
        check(f"helix density is uniform {n1}x{n2}",
              spread < 1e-12 * float(np.max(np.abs(p_site))),
              f"max deviation from the mean {spread:.2e}")

        # Reversing the helix reverses P, which is the whole reason a static
        # field can select one handedness.
        p_reversed = layer_polarization(_helix(positions, lattice, -h, -k, e1, e2),
                                        families)[0]
        check(f"reversing Q reverses P {n1}x{n2}",
              agrees(p_reversed, -p, float(np.linalg.norm(p))),
              f"|P(-Q) + P(Q)| = {float(np.linalg.norm(p_reversed + p)):.3e}")

        check(f"P scales as S^2 {n1}x{n2}",
              np.allclose(layer_polarization(m, families, spin_length=2.0)[0], 4.0 * p,
                          rtol=1e-12),
              "S = 2 gives four times the S = 1 answer")

    # -- the isotropic limit, where the answer is known independently --------
    positions, lattice = _triangular_lattice(24, 24)
    knb = build_families(*positions.T, lattice, single_layer=True, reference=_knb_reference())
    worst = max(
        float(np.max(np.abs(f.matrix - _cross_matrix(
            [np.cos(np.radians(f.angle)), np.sin(np.radians(f.angle)), 0.0]))))
        for f in knb[0]
    )
    check("KNB orbit reproduces [d]_x on every bond", worst < 1e-12,
          f"max deviation {worst:.2e}, the 60 deg branch included")

    # P ~ Q x n for the isotropic coupling, so a proper screw cannot polarize it.
    # The generalized matrices can, and that gap is the whole point of using them.
    h, k = 3, 0
    reciprocal = reciprocal_lattice_from_real(lattice)
    q_vector = h * reciprocal[0] + k * reciprocal[1]
    screw = _helix(positions, lattice, h, k, *_orthonormal_plane(q_vector))
    cycloid = _helix(positions, lattice, h, k, *_orthonormal_plane([0.0, 0.0, 1.0]))
    full = build_families(*positions.T, lattice, single_layer=True)
    p_screw_knb = layer_polarization(screw, knb)[0]
    p_cycloid_knb = layer_polarization(cycloid, knb)[0]
    p_screw_full = layer_polarization(screw, full)[0]
    check("proper screw does not polarize the isotropic coupling",
          agrees(p_screw_knb, 0.0, float(np.linalg.norm(p_cycloid_knb))),
          f"|P_screw| = {float(np.linalg.norm(p_screw_knb)):.2e} against "
          f"|P_cycloid| = {float(np.linalg.norm(p_cycloid_knb)):.3e}")
    check("proper screw does polarize the anisotropic coupling",
          float(np.linalg.norm(p_screw_full)) > 1e-3,
          f"|P| = {float(np.linalg.norm(p_screw_full)):.3e} e Angstrom, carried entirely "
          "by the off-diagonal entries the isotropic form lacks")

    # -- the strongest test: covariance of the whole path ---------------------
    positions, lattice = _triangular_lattice(12, 12)
    families = build_families(*positions.T, lattice, single_layer=True)
    basis = np.linalg.qr(rng.normal(size=(3, 3)))[0]
    m = _helix(positions, lattice, 2, 1, basis[0], basis[1])
    p = layer_polarization(m, families)[0]
    worst = 0.0
    for rotation in d3d_operations():
        rotated_positions = positions @ rotation.T
        rotated_lattice = lattice @ rotation.T
        # Spins are axial, so they pick up the determinant; P is polar and does not.
        rotated_m = float(np.linalg.det(rotation)) * (m @ rotation.T)
        rotated_families = build_families(*rotated_positions.T, rotated_lattice,
                                          single_layer=True)
        got = layer_polarization(rotated_m, rotated_families)[0]
        worst = max(worst, float(np.max(np.abs(got - rotation @ p))))
    check("P is D3d covariant end to end", worst < 1e-12 * float(np.linalg.norm(p)),
          f"max |P(gS on g-lattice) - R_g P| = {worst:.2e} against |P| = "
          f"{float(np.linalg.norm(p)):.3e}, over all 12 operations")

    # -- guards ---------------------------------------------------------------
    positions, lattice = _triangular_lattice(4, 4)
    try:
        build_families(*positions.T, lattice, single_layer=True, shells=(3,))
        check("shell 3 rejects a 4x4 grid", False, "no error raised")
    except ValueError as exc:
        check("shell 3 rejects a 4x4 grid", "counted twice" in str(exc),
              "a bond two cells long wraps onto its own reverse")
    check("shell 1 accepts a 4x4 grid",
          len(build_families(*positions.T, lattice, single_layer=True, shells=(1,))[0]) == 3,
          "the one-cell bond is still unambiguous there")

    rotated30 = lattice @ rotation_z(30.0).T
    try:
        build_families(*(positions @ rotation_z(30.0).T).T, rotated30, single_layer=True)
        check("a 30 deg lattice is rejected", False, "no error raised")
    except ValueError as exc:
        check("a 30 deg lattice is rejected", "not in the D3d orbit" in str(exc),
              "the P-31m setting cannot be mistaken for P-3m1")

    try:
        build_families(*positions.T, lattice, single_layer=True, shells=(2,))
        check("shell 2 is refused", False, "no error raised")
    except ValueError as exc:
        check("shell 2 is refused", "four-state mapping" in str(exc),
              "it points along the mirrors and needs its own matrix")

    # -- bilayer --------------------------------------------------------------
    positions, lattice = _triangular_lattice(12, 12)
    bilayer = np.concatenate([positions, positions + [0.0, 0.0, 6.0]], axis=0)
    basis = np.linalg.qr(rng.normal(size=(3, 3)))[0]
    top = _helix(positions, lattice, 2, 1, basis[0], basis[1])
    bottom = _helix(positions, lattice, -2, -1, basis[0], basis[1])
    families = build_families(*bilayer.T, lattice, single_layer=False)
    check("bilayer splits into two layers", len(families) == 2, f"{len(families)} layer(s)")
    check("no bond crosses the layers",
          all(np.all((f.site_i < 144) == (f.site_j < 144))
              for layer in families for f in layer),
          "each layer is bonded only to itself")
    p = layer_polarization(np.concatenate([top, bottom]), families)
    check("opposite helices cancel between layers",
          agrees(p.sum(axis=0), 0.0, float(np.linalg.norm(p[0])))
          and float(np.linalg.norm(p[0])) > 1e-6,
          f"|P_total| = {float(np.linalg.norm(p.sum(axis=0))):.3e}, "
          f"|P_layer| = {float(np.linalg.norm(p[0])):.3e}")

    print("\nAll checks passed." if failures == 0 else f"\n{failures} check(s) failed.")
    return failures


if __name__ == "__main__":
    if len(sys.argv) > 1:
        main()
    else:
        raise SystemExit(_selftest())
