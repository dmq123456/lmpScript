#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Ferroelectric polarization from the generalized spin-current model.

    P_GSC = sum_{<ij>_n} M^n_ij (S_i x S_j)

where M^n_ij is a 3x3 matrix attached to the bond joining the nth neighbours i
and j. Only the matrix of one reference bond per shell is an independent
quantity -- the one lying along x, obtained by four-state mapping -- and every
other bond in the shell follows from the point group.

Two things fix how that propagation has to be written, and both are easy to get
wrong in a way that survives every test but flips the answer's sign.

Covariance
----------
P is a polar vector, while S_i x S_j is the cross product of two axial vectors
and is therefore axial. Demanding that P = M C hold in every frame gives

    M(R d) = det(R) R M(d) R^T,

and the det(R) is not optional: it is invisible on the three proper rotations
and changes the sign on the six improper ones. A useful consequence is that the
bond antisymmetry needs no separate rule. Inversion has R = -I and det = -1, so
the law already returns M(-d) = -M(d), matching S_i x S_j = -(S_j x S_i). The
orbit is therefore generated by the group action alone.

Setting
-------
NiI2 is P-3m1 (#164), not P-31m (#162): the twofold axes lie along the a axes,
at 0, 60 and 120 degrees, so all six first neighbours sit on a twofold axis and
the reference bond's stabiliser is {E, C2x}. That is what forces the reference
matrix into the five-parameter shape

    [[A, 0, 0], [0, B, C], [0, D, E]],

and the published matrices have exactly that shape, which is an independent
confirmation of the setting -- in the #162 setting x would lie in a mirror
instead and M[0][0] would be forced to zero. `_selftest` asserts the stabiliser
condition, so a lattice rotated by 30 degrees relative to the matrices is
reported rather than silently mis-transformed.

The 60 degree trap
------------------
The three positive first-neighbour directions are a1 (0 deg), a1 + a2 (60 deg)
and a2 (120 deg), but 60 degrees is *not* in the C3 orbit of x: R_z(60) is not
an element of D3d, being R_z(240) times a twofold rotation about z. The 60
degree matrix has to be reached as -M(240 deg). Substituting 60 degrees into
R_z(t) M R_z(t)^T directly gives the wrong sign on M[0][2] and M[2][0] only,
which no symmetry check on the proper rotations alone would catch.

Third neighbours share the first neighbours' directions at twice the distance,
so they reuse this machinery with their own reference matrix. Second neighbours
do not: they point at 30, 90 and 150 degrees, lie in a mirror rather than on a
twofold axis, and their matrix has the complementary shape (zero diagonal, four
free parameters). They are a separate four-state mapping and are deliberately
absent here rather than wrongly generated from M^1.

Run this file directly to execute the self-test; run it on a dump to write the
P(t) time series.
"""

