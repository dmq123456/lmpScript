# ----------------------------------------------------------------------
# Command line: the P(t) time series
# ----------------------------------------------------------------------
def _iter_frames(dump_path: Path, *, vector, element, drop_zero_vector,
                 frame_start, frame_stop, frame_step):
    """Frames one at a time, so a long trajectory never sits in memory at once."""
    from dumpframe import extract, read_one_frame

    scanned = 0
    with Path(dump_path).open() as fh:
        while True:
            if frame_stop is not None and scanned >= frame_stop:
                return
            record = read_one_frame(fh)
            if record is None:
                return
            timestep, box_header, box_lines, columns, atom_lines = record
            if scanned >= frame_start and (scanned - frame_start) % frame_step == 0:
                frame = extract(columns, atom_lines, vector=vector, element=element,
                                drop_zero_vector=drop_zero_vector)
                frame["frame_index"] = scanned
                frame["timestep"] = timestep
                frame["box_header"] = box_header
                frame["box_lines"] = box_lines
                yield frame
            scanned += 1


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="polarization.py",
        description="Write the spin-current polarization P(t) of a dump trajectory.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("input_dump", type=Path, help="Input LAMMPS dump file")
    parser.add_argument("--vector", nargs=3, required=True, metavar=("SX", "SY", "SZ"),
                        help="The three spin columns, e.g. "
                             "--vector 'c_outsp[1]' 'c_outsp[2]' 'c_outsp[3]'")
    parser.add_argument("--element", type=str, default="all",
                        help="Element symbol to include, or 'all'. The sites must be one "
                             "per primitive cell, so a dump holding the iodines too needs "
                             "--element Ni")
    parser.add_argument("--drop-zero-vector", action="store_true",
                        help="Skip atoms whose spin is exactly zero")
    parser.add_argument("--single-layer", action="store_true",
                        help="Treat the frame as one layer instead of splitting at the "
                             "z midpoint into two independently bonded layers")
    parser.add_argument("--shells", type=int, nargs="+", default=list(DEFAULT_SHELLS),
                        metavar="N", help="Neighbour shells to sum over")
    parser.add_argument("--spin-length", type=float, default=1.0, metavar="S",
                        help="Spin length S. P scales as S^2; the reference matrices were "
                             "fitted for the convention this has to match")
    parser.add_argument("--lattice-grid", "--topo-grid", type=int, nargs=2,
                        dest="lattice_grid", metavar=("N1", "N2"), default=None,
                        help="Cell repeats, read off the positions when omitted")
    parser.add_argument("--frame-start", type=int, default=0, help="First frame to read")
    parser.add_argument("--frame-stop", type=int, default=None, help="Stop before this frame")
    parser.add_argument("--frame-step", type=int, default=1, help="Read every nth frame")
    parser.add_argument("--out", type=Path, default=Path("polarization.dat"),
                        help="Output table")
    return parser


def main(argv=None) -> None:
    args = build_parser().parse_args(argv)
    cfg = {
        "single_layer": args.single_layer,
        "shells": tuple(args.shells),
        "spin_length": args.spin_length,
        "lattice_grid": tuple(args.lattice_grid) if args.lattice_grid else None,
    }

    rows: list[tuple] = []
    lattice = None
    n_sites = n_layers = 0
    for frame in _iter_frames(
        args.input_dump, vector=tuple(args.vector), element=args.element,
        drop_zero_vector=args.drop_zero_vector, frame_start=args.frame_start,
        frame_stop=args.frame_stop, frame_step=args.frame_step,
    ):
        per_layer = frame_polarization(frame, cfg)
        if lattice is None:
            lattice = _lattice_from_frame(frame)
            n_sites = int(frame["x"].size)
            n_layers = per_layer.shape[0]
            print(f"[INFO] {n_sites} site(s), {n_layers} layer(s), shells {args.shells}, "
                  f"S = {args.spin_length}")
        rows.append((frame["frame_index"], frame["timestep"],
                     per_layer.sum(axis=0), per_layer))

    if not rows:
        raise SystemExit("No frames were read; check --frame-start/--frame-stop.")

    header = ["frame", "timestep", "Px", "Py", "Pz"]
    if n_layers > 1:
        header += [f"P{c}_L{n + 1}" for n in range(n_layers) for c in "xyz"]
    with args.out.open("w") as fh:
        fh.write(f"# {' '.join(sys.argv)}\n")
        fh.write(f"# sites {n_sites}  layers {n_layers}  shells {tuple(args.shells)}  "
                 f"S {args.spin_length}\n")
        fh.write("# P is the box total in e Angstrom; divide by the site count for the "
                 "value per formula unit\n")
        fh.write("# " + "  ".join(f"{name:>14s}" for name in header)[2:] + "\n")
        for index, timestep, total, per_layer in rows:
            values = [f"{index:>14d}", f"{int(timestep):>14d}"]
            values += [f"{v:>14.6e}" for v in total]
            if n_layers > 1:
                values += [f"{v:>14.6e}" for v in per_layer.ravel()]
            fh.write("  ".join(values) + "\n")

    totals = np.array([row[2] for row in rows])
    mean = totals.mean(axis=0)
    print(f"[INFO] {len(rows)} frame(s) -> {args.out}")
    print(f"[INFO] <P>   = [{mean[0]: .6e} {mean[1]: .6e} {mean[2]: .6e}] e Angstrom")
    print(f"[INFO] <P>/N = [{mean[0] / n_sites: .6e} {mean[1] / n_sites: .6e} "
          f"{mean[2] / n_sites: .6e}] e Angstrom per site")
    areal = areal_pC_per_m(mean, lattice)
    print(f"[INFO] <P>   = [{areal[0]: .6e} {areal[1]: .6e} {areal[2]: .6e}] pC/m")
    print(f"[INFO] rms fluctuation |P - <P>| = "
          f"{float(np.sqrt(((totals - mean) ** 2).sum(axis=1).mean())): .6e} e Angstrom")


